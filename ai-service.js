  /* ====== 4. 处理世界输入 ====== */
  function inferIntent(input) {
    var text = input.trim();
    if (/^(作为作者|从创作角度|这个故事|这段写得|请帮我|元指令|调整文风|不要写|重写)/.test(text)) return "meta";
    if (/[?？]$/.test(text) || /(为什么|为何|是什么|有没有|是否|怎么会|谁是|哪里|多少|吗)$/.test(text)) return "world_question";
    return "world_action";
  }

  function inferLevel(input) {
    if (/(整个世界|所有人|任何人|永远|从来不会|世界里没有|时间只能|死亡意味)/.test(input)) return "L1";
    if (/(规则|法律|制度|习俗|仪式|必须|禁止|每逢|每天|只能通过|共同遵守)/.test(input)) return "L2";
    return "L3";
  }

  function findContradiction(state, input, level) {
    var source = level === "L1" ? state.axioms : level === "L2" ? state.rules : [];
    var negated = input.replace(/不|没有|不能|禁止|从不|并非/g, "");
    for (var i = 0; i < source.length; i++) {
      var item = source[i];
      var old = item.text.replace(/不|没有|不能|禁止|从不|并非/g, "");
      var overlap = 0;
      var chars = [];
      for (var j = 0; j < negated.length; j++) {
        var ch = negated[j];
        if (old.indexOf(ch) !== -1 && chars.indexOf(ch) === -1) {
          chars.push(ch);
          overlap++;
        }
      }
      var hasOppositePolarity = /(不|没有|不能|禁止|从不|并非)/.test(input) !== /(不|没有|不能|禁止|从不|并非)/.test(item.text);
      if (hasOppositePolarity && overlap >= Math.min(6, Math.floor(old.length * .55))) return item;
    }
    return null;
  }

  function entityNameFrom(input) {
    var named = input.match(/(?:叫作|叫做|名为|名字是)([一-龥·]{2,6})/);
    if (named) return named[1];
    var subject = input.match(/^([一-龥·]{2,4})(?:是|把|拿|走|来到|打开|发现|决定)/);
    return subject ? subject[1] : "";
  }

  function locationFrom(input) {
    var result = input.match(/([一-龥]{2,10}(?:城|村|镇|岛|塔|站|室|馆|巷|森林|广场|码头|房间|车站))/);
    return result ? result[1] : "";
  }

