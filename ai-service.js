  function applyPatches(worldState, patches) {
    var next = Object.assign({
      axioms: [],
      rules: [],
      entities: [],
      events: [],
      relationships: [],
      locations: []
    }, JSON.parse(JSON.stringify(worldState || {})));
    for (var i = 0; i < patches.length; i++) {
      var patch = patches[i];
      if (patch.collection === "entityFact") {
        for (var j = 0; j < next.entities.length; j++) {
          if (next.entities[j].name === patch.targetName) {
            if (!Array.isArray(next.entities[j].facts)) next.entities[j].facts = [];
            next.entities[j].facts.push(patch.value);
            break;
          }
        }
      } else if (patch.collection === "relationships") {
        var relation = patch.value || {};
        if (!relation.from || !relation.to) continue;
        var duplicate = next.relationships.some(function (existing) {
          return existing.from === relation.from &&
            existing.to === relation.to &&
            (existing.type || "关联") === (relation.type || "关联");
        });
        if (!duplicate) next.relationships.push(relation);
      } else if (Array.isArray(next[patch.collection])) {
        next[patch.collection].push(patch.value);
      }
    }
    return next;
  }

