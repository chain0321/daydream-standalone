  /** 流式 API 调用：通过 SSE 逐块接收内容，返回 Promise<string> */
  function callAIStream(systemPrompt, userPrompt, opts) {
    opts = opts || {};
    var onChunk = opts.onChunk || function () {};
    var controller = new AbortController();
    var timer = setTimeout(function () { controller.abort(); }, API.timeout);
    var fullContent = "";
    var reasoningLength = 0;
    var finishReason = null;

    return fetch(API.endpoint, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "Authorization": "Bearer " + API.apiKey
      },
      body: JSON.stringify(buildRequestBody(systemPrompt, userPrompt, opts, true)),
      signal: controller.signal
    }).then(function (res) {
      if (!res.ok) {
        return res.text().then(function (body) {
          throw new Error("API " + res.status + ": " + (body || "").slice(0, 200));
        });
      }
      if (!res.body || typeof res.body.getReader !== "function") {
        throw new Error("浏览器不支持流式响应读取");
      }

      var reader = res.body.getReader();
      var decoder = new TextDecoder();
      var buffer = "";

      return new Promise(function (resolve, reject) {
        function processLine(rawLine) {
          var line = rawLine.trim();
          if (!line || line.indexOf("data:") !== 0) return;
          var payload = line.slice(5).trim();
          if (!payload || payload === "[DONE]") return;
          try {
            var json = JSON.parse(payload);
            var choice = json.choices && json.choices[0];
            if (!choice) return;
            if (choice.finish_reason) finishReason = choice.finish_reason;
            var delta = choice.delta;
            if (delta && delta.reasoning_content) {
              reasoningLength += delta.reasoning_content.length;
            }
            if (delta && delta.content) {
              fullContent += delta.content;
              onChunk(delta.content, fullContent);
            }
          } catch (e) {
            console.warn("跳过无法解析的 SSE 数据：" + e.message);
          }
        }

        function finishStream() {
          clearTimeout(timer);
          if (finishReason && finishReason !== "stop") {
            reject(finishReasonError(finishReason));
          } else if (!fullContent.trim() && reasoningLength > 0) {
            reject(new Error("API 返回空内容（stream），reasoning 消耗了输出预算"));
          } else if (!fullContent.trim()) {
            reject(new Error("API 返回空内容（stream）"));
          } else {
            resolve(fullContent.trim());
          }
        }

        function readStream() {
          reader.read().then(function (result) {
            if (result.done) {
              buffer += decoder.decode();
              if (buffer.trim()) processLine(buffer);
              finishStream();
              return;
            }

            buffer += decoder.decode(result.value, { stream: true });
            var lines = buffer.split("\n");
            // 最后一行可能不完整，留到下次
            buffer = lines.pop() || "";

            for (var i = 0; i < lines.length; i++) {
              processLine(lines[i]);
            }

            readStream();
          }).catch(function (err) {
            clearTimeout(timer);
            if (err && err.name === "AbortError") {
              reject(new Error("请求超时"));
            } else {
              reject(err);
            }
          });
        }

        readStream();
      });
    }).catch(function (err) {
      clearTimeout(timer);
      if (err && err.name === "AbortError") throw new Error("请求超时");
      throw err;
    });
  }

  /** 安全解析 JSON：先尝试直接解析，再尝试从文本中提取 JSON */
  function parseJSON(text, fallback) {
    try { return JSON.parse(text); } catch (e) { /* 继续 */ }
    // 尝试提取 ```json ... ``` 代码块
    var m = text.match(/```(?:json)?\s*([\s\S]*?)```/);
    if (m) {
      try { return JSON.parse(m[1].trim()); } catch (e2) { /* 继续 */ }
    }
    // 尝试找到第一个 [ 或 { 开头到对应的闭合
    var start = text.search(/[\[\{]/);
    if (start !== -1) {
      var depth = 0;
      for (var i = start; i < text.length; i++) {
        if (text[i] === "[" || text[i] === "{") depth++;
        if (text[i] === "]" || text[i] === "}") depth--;
        if (depth === 0) {
          try { return JSON.parse(text.slice(start, i + 1)); } catch (e3) { break; }
        }
      }
    }
    return fallback;
  }

